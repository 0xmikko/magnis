#!/usr/bin/env bash
#
# Bake the developer's credentials from a source .env into the bundled
# resource `desktop/src-tauri/resources/magnis.env` that the packaged app's
# launchd services load via MAGNIS_ENV_FILE (DEC-6). Secrets never enter git
# (the output is gitignored) nor the plists (DEC-7).
#
# Usage:
#   bundle-secrets.sh [--fixture] [SRC_ENV]
#     SRC_ENV   source env file (default: repo-root .env)
#     --fixture CI mode: same validation, but the output is marked NOT shippable
#               (DEC-17). Production and fixture share NO fallback — a missing
#               required key always fails the build.
#
# Override the output path with MAGNIS_SECRETS_OUT (used by tests).
#
# Required keys (build FAILS LOUDLY if any is missing/empty — NO FALLBACKS):
#   GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET, GOOGLE_REDIRECT_URI,
#   TELEGRAM_API_ID, TELEGRAM_API_HASH, and at least one of
#   ANTHROPIC_API_KEY / OPENAI_API_KEY (the agent LLM key).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
# Source the file from the crate root (not a resources/ subdir) so Tauri's
# `resources: ["magnis.env"]` lands it flat at Contents/Resources/magnis.env —
# the exact path the service plists set for MAGNIS_ENV_FILE. An array-form
# resource in a subdir would preserve the subdir (Contents/Resources/resources/…)
# and the services would not find it.
OUT="${MAGNIS_SECRETS_OUT:-$REPO_ROOT/desktop/src-tauri/magnis.env}"

# FIXTURE / SRC may also come from the environment so CI can drive the fixed
# `beforeBuildCommand` string without editing it (DEC-17): set
# MAGNIS_SECRETS_FIXTURE=1 and MAGNIS_SECRETS_SRC=<ci-fixture.env>.
FIXTURE="${MAGNIS_SECRETS_FIXTURE:-0}"
SRC=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --fixture) FIXTURE=1; shift ;;
    *) SRC="$1"; shift ;;
  esac
done
SRC="${SRC:-${MAGNIS_SECRETS_SRC:-$REPO_ROOT/.env}}"

if [[ ! -f "$SRC" ]]; then
  echo "bundle-secrets: FATAL — source env file not found: $SRC" >&2
  exit 1
fi

# Read KEY's value from SRC (last assignment wins), stripping surrounding quotes.
# Always exits 0 (empty when absent) so an absent key never trips `set -e`.
getval() {
  { grep -E "^$1=" "$SRC" || true; } | tail -1 | sed -E "s/^$1=//" | sed -E "s/^\"(.*)\"$/\1/; s/^'(.*)'$/\1/"
}

REQUIRED=(GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET GOOGLE_REDIRECT_URI TELEGRAM_API_ID TELEGRAM_API_HASH)
LLM_KEYS=(ANTHROPIC_API_KEY OPENAI_API_KEY)
# Non-secret-ish runtime selectors + the LLM keys, passed through when present.
OPTIONAL=(ANTHROPIC_API_KEY OPENAI_API_KEY DEFAULT_ENGINE EMBEDDING_PROVIDER EMBEDDINGS_PROVIDER EMBEDDING_MODEL OLLAMA_BASE_URL)

missing=()
for k in "${REQUIRED[@]}"; do
  [[ -z "$(getval "$k")" ]] && missing+=("$k")
done
llm_ok=0
for k in "${LLM_KEYS[@]}"; do
  [[ -n "$(getval "$k")" ]] && llm_ok=1
done
[[ $llm_ok -eq 0 ]] && missing+=("one-of:${LLM_KEYS[*]}")

if [[ ${#missing[@]} -gt 0 ]]; then
  echo "bundle-secrets: FATAL — missing required keys in $SRC: ${missing[*]}" >&2
  echo "bundle-secrets: no output written (NO FALLBACKS)." >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo "# Generated by bundle-secrets.sh — DO NOT COMMIT. Baked into Magnis.app."
  if [[ $FIXTURE -eq 1 ]]; then
    echo "# FIXTURE BUILD — placeholder values, NOT a shippable artifact (DEC-17)."
  fi
  for k in "${REQUIRED[@]}"; do
    printf '%s=%s\n' "$k" "$(getval "$k")"
  done
  for k in "${OPTIONAL[@]}"; do
    v="$(getval "$k")"
    [[ -n "$v" ]] && printf '%s=%s\n' "$k" "$v"
  done
} > "$OUT"

chmod 600 "$OUT"
echo "bundle-secrets: wrote $OUT ($(grep -cvE '^#' "$OUT") keys)"
